-- 드라이브 구조를 `프로젝트 / 업무 / 파일`로 바꾸면서, 업무 폴더는 컬럼 없이
-- **제목으로** 찾게 두었다. 비용을 아끼려는 판단이었는데 물음이 바로 왔다 —
-- "업무 제목을 바꾸면 같은 파일이 두 폴더에 생기는 건가?"
--
-- 파일이 복제되지는 않는다. 대신 **한 업무의 파일이 두 폴더로 갈라진다**
-- (바꾸기 전 파일은 옛 이름 폴더, 그 뒤 파일은 새 이름 폴더). 훑어보기 편하려고
-- 만든 구조인데 그게 깨지므로 말이 안 된다.
--
-- 그래서 프로젝트에 한 것과 같이 한다: 폴더 id를 적어 두고, 제목이 바뀌면
-- 폴더 이름을 따라가게 한다. `projects.drive_folder_id`(0006)와 같은 자리다.
-- ============================================================================

alter table public.cards add column if not exists drive_folder_id text;

comment on column public.cards.drive_folder_id is
  '드라이브의 이 업무 폴더. 첫 업로드 때 채워지고, 제목이 바뀌면 폴더 이름이 따라간다';

