-- ── 1. 동아리 순서 ───────────────────────────────────────────────────────────
alter table public.groups add column if not exists position int;
update public.groups g set position = t.rn
from (select id, row_number() over (partition by type order by created_at, name) as rn
      from public.groups) t
where t.id = g.id and g.position is null;

create or replace function public.reorder_clubs(ids uuid[])
returns void language sql security definer set search_path = public, pg_temp
as $$
  update public.groups g set position = t.ord
  from (select unnest(ids) as id, generate_subscripts(ids, 1) as ord) t
  where g.id = t.id and g.type = 'club' and public.is_approved();
$$;
revoke all on function public.reorder_clubs(uuid[]) from public;
grant execute on function public.reorder_clubs(uuid[]) to authenticated;

