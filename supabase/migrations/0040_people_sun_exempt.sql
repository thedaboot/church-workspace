-- "순원 추가에서 신효진·임성빈은 제외 — 부장님·전도사님이시니까." 두 분은 명단에는 있어야
-- 하지만(출석·직분·생일) 순원 후보에는 오르면 안 된다. 이름을 코드에 박지 않고(§6-26)
-- 명단 속성 한 칸으로 둔다: sun_exempt = 순 편성 대상이 아닌 사역자(교역자·부장).
-- is_pastor와 겹치지 않는다 — 교역자 자격(권한)과 편성 제외(화면 후보)는 다른 물음이다.
-- ============================================================================
alter table public.people add column if not exists sun_exempt boolean not null default false;
update public.people set sun_exempt = true where name in ('신효진', '임성빈') and removed_at is null;
