-- 0041 — 같은 이름의 순·동아리 막기 (2026-09-03 사용자 결정)
-- ----------------------------------------------------------------------------
-- 순은 연도마다 편성이 새로 나므로 **같은 해 안에서만** 이름이 유일하다(26년 오순도순과 27년
-- 오순도순은 공존). 동아리는 year가 null이라 coalesce(year, 0)으로 한 벌에 묶인다. 환송(removed_at)한
-- 것은 빼서 같은 이름으로 다시 만들 수 있다. 화면은 저장 전에 미리 확인해 "같은 이름의 순이 이미
-- 있어요(2026년)"라고 말하고, 이 색인은 마지막 방어선이다(HANDOFF §6 RLS·저장).
-- ============================================================================
create unique index if not exists groups_unique_name
  on public.groups (type, name, coalesce(year, 0)) where removed_at is null;
