// 제목 글자 다듬기 — 유튜브에서 받은 제목을 앱이 쓰는 평범한 글자로 되돌린다.
// ----------------------------------------------------------------------------
// React도 import.meta.env도 쓰지 않는 순수 모듈이라 서버리스 함수에서 그냥 import된다
// (notifyText.js와 같은 자리 — api/push.js가 그 파일을 그렇게 쓴다).
//
// **왜 있나**: "유튜브 링크로 가져오면 제목이 가끔 볼드로 들어온다"(사용자 보고
// 2026-09-08). 우리 화면은 제목을 <input>과 평범한 <span>에만 넣으므로 마크다운
// 굵게가 될 길이 없다 — 굵어 보이는 것은 **글자 자체가 다른 글자**이기 때문이다.
// 채널들이 제목을 눈에 띄게 하려고 유니코드 수학 알파벳(𝗪𝗼𝗿𝘀𝗵𝗶𝗽 = U+1D5E6 부근)이나
// 전각(Ｗｏｒｓｈｉｐ), 모양낸 숫자(𝟭)로 적어 두는데, 그 코드 자리는 글꼴이 처음부터
// 굵은 모양으로 그린다. CSS로는 되돌릴 수 없고 고칠 자리는 하나뿐이다 — 받은 글자를
// 정규화해서 평범한 글자로 접는 것.
//
// NFKC가 그 일을 한다(호환 문자를 표준 글자로 접는 정규화). 수학 볼드·이탤릭·전각·
// 둥근 숫자가 다 아스키로 내려오고, **한글과 이모지는 그대로 남는다** — NFKC가 접는
// 것은 '같은 글자의 다른 표기'뿐이다.
//
// NFKC가 손대지 않는 것 둘은 따로 턴다:
//   · 폭 없는 글자(U+200B~U+200D · U+FEFF) — 눈에 안 보이면서 제목 비교를 어긋나게 한다
//   · 변이 선택자(U+FE0F) — 앞 글자를 이모지 모양으로 그리라는 표시라 제목에 쓸 일이 없다
// 마지막으로 공백을 하나로 접고 앞뒤를 턴다. 제목은 한 줄짜리 값이라 줄바꿈·연속 공백이
// 그대로 남으면 목록에서 줄이 흔들린다.
// ============================================================================
export function cleanTitle(s) {
  return String(s ?? '')
    .normalize('NFKC')
    .replace(/[\u200B-\u200D\uFEFF\uFE0F]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
