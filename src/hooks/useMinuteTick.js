import { useEffect, useState } from 'react';

// ============================================================================
// 1분 틱 — 화면에 떠 있는 상대 시간 라벨('5분 전 다녀감')을 스스로 늙게 한다.
// ----------------------------------------------------------------------------
// agoLabel·formatRelative는 그릴 때의 Date.now()로 글자를 만든다. 그래서 멤버 모달이나
// 대시보드를 열어 두면 **그 값이 굳어서** 삼십 분이 지나도 '5분 전'이다(사용자 지적
// 2026-08-30 — "제대로 갱신되는 건지 모르겠다").
//
// 고치는 방법은 그 라벨이 있는 컴포넌트만 1분마다 다시 그리게 하는 것이다.
// **틱은 숫자 하나다**(분 단위로 자른 Date.now()) — 매번 새 객체·새 배열을 state로 두면
// useSyncExternalStore를 쓰는 자리들처럼 무한 리렌더가 된다(§4.9). 값이 같으면 리액트가
// 알아서 다시 그리지 않으므로, 타이머가 어긋나게 깨어나도 헛렌더가 되지 않는다.
//
// **쓰는 컴포넌트에만 붙인다.** 앱 뿌리에 두면 1분마다 화면 전체가 다시 그려진다.
// 절대 시각을 그리는 자리(업무 창 댓글의 formatDate처럼 '8월 30일 오후 3:12')는 늙지
// 않으므로 붙이지 않는다.
// ============================================================================
export const minuteOf = (ms = Date.now()) => Math.floor(ms / 60000);

export function useMinuteTick() {
  const [minute, setMinute] = useState(minuteOf);
  useEffect(() => {
    const id = setInterval(() => setMinute(minuteOf()), 60000);
    return () => clearInterval(id);
  }, []);
  return minute;
}
