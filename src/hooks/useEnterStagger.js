import { useEffect, useRef } from 'react';

// ============================================================================
// 등장 순차 애니메이션(stagger)을 **처음 한 번만** 준다.
// ----------------------------------------------------------------------------
// 목록의 줄마다 animationDelay를 순번대로 주면 처음 열 때는 위에서 아래로 차례차례
// 들어와 보기 좋다. 그런데 그 순번을 계속 주면, 목록이 처음 뜬 뒤에 **새로 붙는 한 줄**
// 에도 순번 지연이 걸린다. `.dc-row`/`.dc-card`는 fill-mode가 `both`라 지연 동안
// 투명하므로, 그 줄은 몇백 ms 동안 아무 데도 없다가 뒤늦게 나타난다.
//
// 실제로 이렇게 보였다(사용자 지적 2026-08-31 — "순차 애니메이션 순서가 종종 이상하다"):
//  · 마감 목록에서 업무를 완료로 옮기면 그 줄이 '끝낸 업무' 구간으로 **다시 마운트**되고,
//    그 구간이 목록의 열두 번째쯤이라 264ms 뒤에 혼자 뿅 나타났다. 나머지 줄은 가만히
//    있으니 "순서"가 아니라 지각으로 읽혔다.
//  · 보드에서 카드를 다른 컬럼으로 끌어다 놓으면 같은 이유로 드롭 연출(220ms)이 끝난
//    **뒤에** 카드가 최대 240ms 더 사라져 있었다.
//
// 그래서 순번은 첫 렌더에서만 쓰고, 그다음부터 새로 붙는 줄은 지연 없이 바로 나타난다.
// 목록이 통째로 갈리는 경우(다른 화면으로 갔다 오기)는 컴포넌트가 다시 마운트되므로
// 순차 등장이 그대로 남는다.
// ============================================================================
export function useEnterStagger() {
  const first = useRef(true);
  useEffect(() => { first.current = false; }, []);
  return first.current;
}
